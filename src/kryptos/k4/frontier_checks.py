def reconstruction_plain(candidate: str = "solvekryptos_field_guide") -> dict[int, str]:
    """All 97 letters of a published reconstruction, position -> letter."""
    from .plaintext_evidence import reconstructed_plaintext

    text = reconstructed_plaintext(candidate)
    if text is None:
        raise ValueError(f"no 97-letter reconstruction registered as {candidate!r}")
    return dict(enumerate(text))


def _periodic_consistent(kv: dict[int, int], p: int) -> bool:
    slots: dict[int, int] = {}
    return all(slots.setdefault(i % p, k) == k for i, k in kv.items())


def reconstruction_suite(
    candidate: str = "solvekryptos_field_guide",
    ciphertext: str = K4,
    include_dictionary: bool = False,
    columnar_widths: Iterable[int] = range(2, 9),
) -> dict[str, Any]:
    """Could *any* tested family turn the reconstructed plaintext into K4?

    Uses all 97 letters as known plaintext, so periods up to 48 and more are testable. A
    survivor would be a strong lead (it fits 97 letters, not 24); zero survivors means the
    reconstruction is not the output of that family, whatever the key.
    """
    from . import crib_constraints as cc
    from . import structural_checks as sc

    plain = reconstruction_plain(candidate)
    out: dict[str, Any] = {
        "candidate": candidate,
        "english_z_of_reconstruction": round(english_z("".join(plain.values())), 3),
    }
    periodic = {}
    for name, (alpha, fn) in families().items():
        kv = key_values(alpha, fn, ciphertext, plain)
        periodic[name] = [p for p in range(1, 49) if _periodic_consistent(kv, p)]
    out["periodic_1_48"] = periodic
    out["monoalphabetic_conflicts"] = len(cc.monoalphabetic_conflicts(ciphertext, plain))
    out["ciphertext_autokey"] = {k: v["survivors"] for k, v in cc.ciphertext_autokey(ciphertext, plain).items()}
    out["plaintext_autokey"] = {k: v["survivors"] for k, v in cc.plaintext_autokey(ciphertext, plain).items()}
    out["linear_key"] = cc.linear_key(ciphertext, plain)
    out["progressive_key_1_48"] = cc.progressive_key(ciphertext, plain, periods=range(1, 49))
    out["double_periodic_p_le_45"] = cc.double_periodic_consistency(45, ciphertext, plain)
    out["recurrence_key_1_40"] = recurrence_key(40, ciphertext, plain)
    out["general_alphabet_periodic_1_48"] = general_alphabet_periodic(48, ciphertext, plain)
    out["hill_2_9"] = sc.hill_consistency(range(2, 10), ciphertext, plain)
    out["dial_keys"] = {
        k: {d: len(v) for d, v in fam.items()} for k, fam in dial_key_scan(None, ciphertext, plain).items()
    }
    # Keystream as English: a running key from any English text.
    keystreams = {}
    for name, (alpha, fn) in families().items():
        kv = key_values(alpha, fn, ciphertext, plain)
        key_alpha = alpha if name.startswith("quagmire") else STANDARD
        ks = "".join(key_alpha[kv[i]] for i in range(len(ciphertext)))
        keystreams[name] = {"keystream": ks, "english_z": round(english_z(ks), 3)}
    out["running_key_keystreams"] = keystreams

    def _survivors(scan: dict[str, Any]) -> int:
        return sum(
            v["survivors"]
            for model in ("sub_then_trans", "trans_then_sub")
            for fam in scan[model].values()
            for v in fam.values()
        )

    col = cc.columnar_period_scan(widths=columnar_widths, periods=range(1, 49), ciphertext=ciphertext, plain=plain)
    out["columnar_period_1_48"] = {w: _survivors(r) for w, r in col.items()}
    geo = cc.geometry_period_scan(periods=range(1, 49), ciphertext=ciphertext, plain=plain)
    out["geometry_period_1_48"] = _survivors(geo)
    rot = sc.double_rotation_period_scan(periods=range(1, 49), ciphertext=ciphertext, plain=plain)
    out["double_rotation_period_1_48"] = _survivors(rot)
    out["bearing_route_period_1_48"] = _survivors(
        bearing_route_scan(periods=range(1, 49), ciphertext=ciphertext, plain=plain)
    )
    if include_dictionary:
        _, words = cc.dictionary_source()
        kw = cc.keyword_alphabet_scan(words, periods=range(1, 49), ciphertext=ciphertext, plain=plain)
        out["keyword_alphabets_1_48"] = {
            q: sum(v["survivors"] for v in kw[q].values()) for q in ("quagmire1", "quagmire2", "quagmire3")
        }
        q4 = cc.quagmire4_dictionary_scan(words, periods=range(1, 49), ciphertext=ciphertext, plain=plain)
        out["quagmire4_dictionary_1_48"] = sum(v["survivors"] for v in q4["periods"].values())
    return out


DEFAULT_FRONTIER_ARTIFACT = "K4_FRONTIER_NULL.json"


def run_frontier_suite(
    artifact_path: str | None = DEFAULT_FRONTIER_ARTIFACT,
    heavy: bool = True,
    include_dictionary: bool = False,
) -> dict[str, Any]:
    """Run every frontier check on K4 (and the reconstruction suite), write one artifact.

    ``heavy`` adds the Hill 5x5 search (about a minute), the columnar English running-key
    scan and the reconstruction suite (a few minutes). ``include_dictionary`` adds the
    dictionary Quagmire scans to the reconstruction suite.
    """
    import json
    import os
    import threading
    from datetime import datetime, timezone
    from pathlib import Path

    summary: dict[str, Any] = {
        "status": "complete",
        "timestamp": datetime.now(timezone.utc).isoformat().replace("+00:00", "Z"),
        "running_key_english": running_key_english(),
        "recurrence_key": recurrence_key(),
        "general_alphabet_periodic": general_alphabet_periodic(),
        "general_alphabet_control_rate_p12": general_alphabet_control_rate(12, trials=100),
        "dial_keys": {k: {d: len(v) for d, v in fam.items()} for k, fam in dial_key_scan().items()},
        "bearing_routes": _route_survivors(bearing_route_scan()),
        "hill_4x4": hill_exhaustive((4,))[4],
        "vocabulary_phrase_keys": vocabulary_phrase_keys(),
    }
    if heavy:
        summary["hill_5x5"] = hill_rowspace_search(5)
        wide = wide_columnar_scan(widths=range(10, 12))
        summary["wide_columnar_10_11"] = {
            w: {m: sum(e["survivors"] for fam in r[m].values() for e in fam.values()) for m in r}
            for w, r in wide.items()
        }
        summary["columnar_running_key_english"] = transposition_running_key_english()
        summary["reconstruction"] = reconstruction_suite(include_dictionary=include_dictionary)
    if artifact_path:
        path = Path(artifact_path)
        tmp = path.with_name(f"{path.name}.{os.getpid()}.{threading.get_ident()}.tmp")
        tmp.write_text(json.dumps(summary, indent=2, default=str))
        os.replace(tmp, path)
    return summary


