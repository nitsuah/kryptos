def _det_mod(m: np.ndarray, q: int) -> int:
    a = [[int(x) % q for x in row] for row in m]
    n, det = len(a), 1
    for c in range(n):
        p = next((r for r in range(c, n) if a[r][c]), None)
        if p is None:
            return 0
        if p != c:
            a[c], a[p] = a[p], a[c]
            det = -det
        det = det * a[c][c] % q
        inv = pow(a[c][c], q - 2, q)
        for r in range(c + 1, n):
            f = a[r][c] * inv % q
            a[r] = [(x - f * y) % q for x, y in zip(a[r], a[c], strict=True)]
    return det % q


def _invertible_mod26(m: np.ndarray) -> bool:
    return _det_mod(m, 2) != 0 and _det_mod(m, 13) != 0


def _row_solutions(n: int, blocks_c: np.ndarray, targets: np.ndarray) -> np.ndarray:
    """All rows x in Z26^n with blocks_c @ x == targets (mod 26), by exhaustive search."""
    sols = []
    grid = np.array(list(itertools.product(range(26), repeat=n - 1)), dtype=np.int64) if n > 1 else None
    for first in range(26):
        x = np.concatenate([np.full((len(grid), 1), first), grid], axis=1)
        ok = np.all((x @ blocks_c.T) % 26 == targets[None, :], axis=1)
        sols.append(x[ok])
    return np.concatenate(sols) if sols else np.zeros((0, n), dtype=np.int64)


def _noncrib_text(text: str, plain: dict[int, str]) -> str:
    return "".join(ch for i, ch in enumerate(text) if i not in plain)


def hill_exhaustive(
    sizes: Iterable[int] = (4,),
    ciphertext: str = K4,
    plain: dict[int, str] | None = None,
    max_matrices: int = 200_000,
) -> dict[int, list[dict[str, Any]]]:
    """Every Hill matrix consistent with the crib blocks, decrypted and scored.

    Decryption is P = K C blockwise (K invertible mod 26; this also covers C = M P with
    K = M^-1). Each row of K is solved separately by exhaustive search over Z26^n. For n = 4
    the four crib blocks leave only a handful of rows, so every full matrix is decrypted and
    the non-crib text scored with ``english_z``. Reports, per alignment, how many invertible
    matrices exist and the best score. A true key would score like English (about 1).
    """
    plain = plain if plain is not None else crib_letters()
    cv = np.array([STANDARD.index(c) for c in ciphertext])
    out: dict[int, list[dict[str, Any]]] = {}
    for n in sizes:
        res = []
        for offset in range(n):
            blocks = [b for b in range(offset, len(ciphertext) - n + 1, n) if all(i in plain for i in range(b, b + n))]
            if len(blocks) < n - 1:
                res.append({"offset": offset, "blocks": len(blocks), "status": "too few blocks"})
                continue
            bc = np.array([[cv[i] for i in range(b, b + n)] for b in blocks])
            row_sols = []
            for r in range(n):
                t = np.array([STANDARD.index(plain[b + r]) for b in blocks])
                row_sols.append(_row_solutions(n, bc, t))
            combos = math.prod(len(s) for s in row_sols)
            entry: dict[str, Any] = {
                "offset": offset,
                "blocks": len(blocks),
                "row_solutions": [len(s) for s in row_sols],
            }
            if combos == 0:
                entry["status"] = "no consistent matrix"
            elif combos > max_matrices:
                entry["status"] = f"{combos} matrices; too many to decrypt one by one"
            else:
                best, invertible = -9.0, 0
                full_blocks = range(offset, len(ciphertext) - n + 1, n)
                for rows in itertools.product(*row_sols):
                    k = np.array(rows)
                    if not _invertible_mod26(k):
                        continue
                    invertible += 1
                    text = [""] * len(ciphertext)
                    for b in full_blocks:
                        pv = (k @ cv[b : b + n]) % 26
                        for j in range(n):
                            text[b + j] = STANDARD[pv[j]]
                    body = _noncrib_text("".join(text), plain)
                    best = max(best, english_z(body))
                entry.update(
                    {"status": "decrypted", "invertible_matrices": invertible, "best_english_z": round(best, 3)}
                )
            res.append(entry)
        out[n] = res
    return out


def hill_rowspace_search(
    n: int = 5,
    ciphertext: str = K4,
    plain: dict[int, str] | None = None,
    max_matrices: int = 20_000_000,
    top: int = 200,
    chunk: int = 500_000,
) -> list[dict[str, Any]]:
    """Hill n x n where the crib blocks leave a few choices per row: score every matrix.

    For each alignment, every row of K consistent with the crib blocks is found. When the
    number of full matrices is at most ``max_matrices`` (for 5x5 with four crib blocks, 26 per
    row, so 26**5), every matrix is used to decrypt K4 and scored with the quadgram model;
    the ``top`` best are checked for invertibility and their non-crib text scored with
    ``english_z``. A true key would score like English (about 1); K4's best stays near noise.
    """
    plain = plain if plain is not None else crib_letters()
    cv = np.array([STANDARD.index(c) for c in ciphertext])
    table4 = _gram_index(4)
    out = []
    for offset in range(n):
        blocks = [b for b in range(offset, len(ciphertext) - n + 1, n) if all(i in plain for i in range(b, b + n))]
        entry: dict[str, Any] = {"offset": offset, "blocks": len(blocks)}
        if len(blocks) < n - 1:
            out.append({**entry, "status": "too few blocks"})
            continue
        bc = np.array([[cv[i] for i in range(b, b + n)] for b in blocks])
        rows = [fc_row for fc_row in (
            _row_solutions(n, bc, np.array([STANDARD.index(plain[b + r]) for b in blocks])) for r in range(n)
        )]  # fmt: skip
        entry["row_solutions"] = [len(r) for r in rows]
        total = math.prod(len(r) for r in rows)
        if total == 0:
            out.append({**entry, "status": "no consistent matrix"})
            continue
        if total > max_matrices:
            out.append({**entry, "status": f"{total} matrices; above the search limit"})
            continue
        full = np.array([cv[b : b + n] for b in range(offset, len(ciphertext) - n + 1, n)])  # (nb, n)
        letters = [(r @ full.T) % 26 for r in rows]  # per row: (choices, nb)
        sizes = [len(r) for r in rows]
        best_scores: list[tuple[float, tuple[int, ...]]] = []
        for lo in range(0, total, chunk):
            idx = np.arange(lo, min(total, lo + chunk))
            choice = np.stack(np.unravel_index(idx, sizes), axis=1)  # (m, n)
            text = np.stack([letters[r][choice[:, r]] for r in range(n)], axis=2).reshape(len(idx), -1)
            q = text[:, :-3] * 17576 + text[:, 1:-2] * 676 + text[:, 2:-1] * 26 + text[:, 3:]
            score = table4[q].mean(axis=1)
            keep = np.argsort(score)[-top:]
            best_scores += [(float(score[k]), tuple(int(x) for x in choice[k])) for k in keep]
            best_scores = sorted(best_scores)[-top:]
        best_z, invertible = -9.0, 0
        for _, ch in best_scores:
            k = np.array([rows[r][ch[r]] for r in range(n)])
            if not _invertible_mod26(k):
                continue
            invertible += 1
            txt = [""] * len(ciphertext)
            for b in range(offset, len(ciphertext) - n + 1, n):
                pv = (k @ cv[b : b + n]) % 26
                for j in range(n):
                    txt[b + j] = STANDARD[pv[j]]
            best_z = max(best_z, english_z(_noncrib_text("".join(txt), plain)))
        out.append({**entry, "status": "searched", "matrices": total, "invertible_in_top": invertible,
                    "best_english_z": round(best_z, 3)})  # fmt: skip
    return out


def _dense_table(n: int) -> np.ndarray:
    from .english_model import table

    grams, floor = table(n) if n > 2 else _bigram_table()
    arr = np.full(26**n, floor, dtype=np.float32)
    for g, v in grams.items():
        idx = 0
        for ch in g:
            idx = idx * 26 + STANDARD.index(ch)
        arr[idx] = v
    return arr


def _bigram_table() -> tuple[dict[str, float], float]:
    from pathlib import Path

    from kryptos.paths import get_repo_root

    path = Path(get_repo_root()) / "data" / "ngrams" / "english_2grams.tsv"
    grams, floor = {}, -10.0
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("# floor"):
            floor = float(line.split("\t")[1])
        elif line and not line.startswith("#"):
            g, v = line.split("\t")
            grams[g] = float(v)
    return grams, floor


def hill_beam_search(
    n: int = 5,
    offsets: Iterable[int] | None = None,
    ciphertext: str = K4,
    plain: dict[int, str] | None = None,
    beam: int = 3000,
) -> list[dict[str, Any]]:
    """Hill n x n where the cribs leave too many matrices to list: build K row by row.

    Row r of K produces plaintext letter r of every block. Rows are added in order and the
    partial texts ranked by the English n-gram model over the letters decided so far (bigrams
    after two rows, trigrams after three, quadgrams after that); the best ``beam`` partial
    matrices survive each step. A heuristic, so the tier is statistical, but a planted key is
    recovered (see tests), and K4's best stays near noise.
    """
    plain = plain if plain is not None else crib_letters()
    cv = np.array([STANDARD.index(c) for c in ciphertext])
    tables = {2: _dense_table(2), 3: _dense_table(3), 4: _dense_table(4)}
    offsets = list(offsets) if offsets is not None else list(range(n))
    out = []
    for offset in offsets:
        blocks = [b for b in range(offset, len(ciphertext) - n + 1, n) if all(i in plain for i in range(b, b + n))]
        full = np.array([cv[b : b + n] for b in range(offset, len(ciphertext) - n + 1, n)])  # (nb, n)
        rows = [
            _row_solutions(n, np.array([[cv[i] for i in range(b, b + n)] for b in blocks]).reshape(len(blocks), n),
                           np.array([STANDARD.index(plain[b + r]) for b in blocks]))
            if blocks else np.array(list(itertools.product(range(26), repeat=n)))
            for r in range(n)
        ]  # fmt: skip
        entry: dict[str, Any] = {"offset": offset, "blocks": len(blocks), "row_solutions": [len(r) for r in rows]}
        if any(len(r) == 0 for r in rows):
            out.append({**entry, "status": "no consistent matrix"})
            continue
        letters = [(r @ full.T) % 26 for r in rows]  # per row: (choices, nb)
        states = [(0.0, (i,)) for i in range(len(rows[0]))]
        for r in range(1, n):
            size = min(r + 1, 4)
            cand_scores, cand_states = [], []
            prev = np.array([s[1] for s in states])  # (S, r)
            for j in range(len(rows[r])):
                cols = [letters[q][prev[:, q]] for q in range(r)] + [
                    np.broadcast_to(letters[r][j], (len(prev), full.shape[0]))
                ]
                window = np.stack(cols[-size:], axis=2)  # (S, nb, size)
                idx = np.zeros(window.shape[:2], dtype=np.int64)
                for t in range(size):
                    idx = idx * 26 + window[:, :, t]
                sc = tables[size][idx].mean(axis=1)
                cand_scores.append(sc)
                cand_states.append(j)
            allsc = np.stack(cand_scores, axis=1)  # (S, J)
            flat = np.argsort(allsc, axis=None)[-beam:]
            si, ji = np.unravel_index(flat, allsc.shape)
            states = [
                (float(allsc[a, b]), tuple(states[a][1]) + (cand_states[b],)) for a, b in zip(si, ji, strict=True)
            ]
        best_z, invertible = -9.0, 0
        for _, choice in sorted(states)[-200:]:
            k = np.array([rows[r][choice[r]] for r in range(n)])
            if not _invertible_mod26(k):
                continue
            invertible += 1
            txt = [""] * len(ciphertext)
            for b in range(offset, len(ciphertext) - n + 1, n):
                pv = (k @ cv[b : b + n]) % 26
                for j in range(n):
                    txt[b + j] = STANDARD[pv[j]]
            best_z = max(best_z, english_z(_noncrib_text("".join(txt), plain)))
        out.append({**entry, "status": "beam", "invertible_in_top": invertible, "best_english_z": round(best_z, 3)})
    return out


