"""Checks for the K4 gaps that the crib-constraint engine left open.

Each gap in ``docs/analysis/K4_NEGATIVE_SPACE.md`` was open because the 24 crib letters
alone can't pin the family down. Every check here adds the one assumption that makes the
family testable, says what that assumption is, and has a planted-solution test.

- ``running_key_english``: a running key from *any* English text (not a known one). The
  key letters at the two crib runs (13 and 11 consecutive letters) would then be English
  fragments themselves. Scored with a real n-gram model against English and random.
- ``transposition_running_key_english``: the same, after every columnar transposition.
- ``recurrence_key``: keys longer than any period, generated by a linear recurrence
  K[i] = c1*K[i-1] + ... + cn*K[i-n] + d (mod 26); Gromark and Fibonacci keys are cases.
- ``general_alphabet_periodic``: a periodic key after an *arbitrary* monoalphabetic step on
  either side. This models letter-swap masking and any mixed alphabet, not just keyword ones.
- ``dial_key_scan``: a key read from a dial (clock face, compass, 24-hour ring) that advances
  a fixed step per letter.
- ``bearing_route_scan``: the text read off a grid along a compass bearing, every whole
  degree, with a periodic key: the "route driven by the compass-rose bearing" for any bearing.
- ``hill_exhaustive``: Hill 4x4 (every matrix consistent with the cribs, decrypted and scored)
  and Hill 5x5 (row by row).
- ``reconstruction_suite``: every family above and in ``crib_constraints`` run against the
  solvekryptos.com reconstruction of the full plaintext, as if all 97 letters were known.
"""

