# ── Running key from an unknown English text ────────────────────────────────


def _runs(positions: Iterable[int]) -> list[list[int]]:
    runs: list[list[int]] = []
    for i in sorted(positions):
        if runs and i == runs[-1][-1] + 1:
            runs[-1].append(i)
        else:
            runs.append([i])
    return runs


def _pair_score(texts: list[str]) -> float:
    """Length-weighted mean of english_z over several fragments."""
    total = sum(len(t) for t in texts)
    return sum(english_z(t) * len(t) for t in texts) / total


def running_key_english(
    ciphertext: str = K4,
    plain: dict[int, str] | None = None,
    keyword: str = "KRYPTOS",
    samples: int = 2000,
    seed: int = 0,
) -> dict[str, Any]:
    """Would the key letters at the crib runs pass as English text?

    For each family, the key letters over each consecutive crib run are scored with
    ``english_z``. ``p_english`` is the share of real English fragment pairs (same lengths,
    independent positions) that score at or below the observed value: small means a running
    key taken from English text is implausible for that family.
    """
    plain = plain if plain is not None else crib_letters()
    runs = [r for r in _runs(plain) if len(r) >= 4]
    lengths = [len(r) for r in runs]
    rng = random.Random(seed)
    eng = reference_english()
    ref = []
    for _ in range(samples):
        frags = []
        for n in lengths:
            s = rng.randrange(0, len(eng) - n)
            frags.append(eng[s : s + n])
        ref.append(_pair_score(frags))
    ref.sort()
    out: dict[str, Any] = {"runs": [[r[0], r[-1]] for r in runs], "families": {}}
    for name, (alpha, fn) in families(keyword).items():
        kv = key_values(alpha, fn, ciphertext, plain)
        # A running key is read in the standard alphabet for the direct families and in the
        # keyed alphabet for the Quagmire ones (key letter = alphabet[key value]).
        key_alpha = alpha if name.startswith("quagmire") else STANDARD
        frags = ["".join(key_alpha[kv[i]] for i in r) for r in runs]
        score = _pair_score(frags)
        p_eng = sum(1 for v in ref if v <= score) / len(ref)
        out["families"][name] = {"key_fragments": frags, "score": round(score, 3), "p_english": p_eng}
    return out


def _gram_index(n: int = 4) -> np.ndarray:
    """Dense log10 table over all 26**n grams (unseen grams get the floor)."""
    from .english_model import table

    grams, floor = table(n)
    arr = np.full(26**n, floor, dtype=np.float32)
    for g, v in grams.items():
        idx = 0
        for ch in g:
            idx = idx * 26 + STANDARD.index(ch)
        arr[idx] = v
    return arr


def _batch_mean_logp(vals: np.ndarray, runs: list[np.ndarray], table4: np.ndarray) -> np.ndarray:
    """Mean quadgram log10 probability per row, over the given column runs."""
    total = np.zeros(vals.shape[0], dtype=np.float64)
    count = 0
    for cols in runs:
        v = vals[:, cols].astype(np.int64)
        idx = v[:, :-3] * 17576 + v[:, 1:-2] * 676 + v[:, 2:-1] * 26 + v[:, 3:]
        total += table4[idx].sum(axis=1)
        count += idx.shape[1]
    return total / count


def transposition_running_key_english(
    widths: Iterable[int] = range(2, 9),
    ciphertext: str = K4,
    plain: dict[int, str] | None = None,
    keyword: str = "KRYPTOS",
    controls: int = 5,
    seed: int = 0,
) -> dict[str, Any]:
    """Columnar transposition + a running key from any English text, either layer order.

    For every column order, the key letters at the crib runs are scored by quadgram model;
    the best row is compared with the best row for ``controls`` shuffled ciphertexts (the
    multiple-testing baseline). A real hit would sit well above the control maxima.
    """
    from .crib_constraints import _columnar_pt_to_ct

    plain = plain if plain is not None else crib_letters()
    positions = np.array(sorted(plain))
    col_of = {p: j for j, p in enumerate(sorted(plain))}
    runs = [np.array([col_of[i] for i in r]) for r in _runs(plain) if len(r) >= 4]
    table4 = _gram_index(4)
    rng = random.Random(seed)
    texts = [ciphertext] + ["".join(rng.sample(ciphertext, len(ciphertext))) for _ in range(controls)]
    fams = families(keyword)
    out: dict[str, Any] = {}
    for w in widths:
        perms = np.array(list(itertools.permutations(range(w))), dtype=np.int16)
        start = _columnar_pt_to_ct(w, perms, len(ciphertext))
        cpos = start[:, positions % w] + positions // w
        per_w: dict[str, Any] = {}
        for model in ("sub_then_trans", "trans_then_sub"):
            best: dict[str, list[float]] = {}
            for text in texts:
                for name, (alpha, fn) in fams.items():
                    cv = np.array([alpha.index(ch) for ch in text])
                    pv = np.array([alpha.index(plain[i]) for i in sorted(plain)])
                    if model == "sub_then_trans":
                        c_at = cv[cpos]  # key applied at the plaintext position, before transposing
                    else:
                        # trans_then_sub: key runs along the ciphertext; the crib letter t sits at
                        # ciphertext position cpos[:, t], so the key letters there are not a run.
                        # Score the key in ciphertext order instead: sort each row by position.
                        c_at = cv[cpos]
                    kv = np.vectorize(fn)(c_at, pv[None, :])
                    if name.startswith("quagmire"):
                        ka = np.array([STANDARD.index(ch) for ch in alpha])
                        kv = ka[kv]
                    if model == "trans_then_sub":
                        order = np.argsort(cpos, axis=1)
                        kv = np.take_along_axis(kv, order, axis=1)
                        sorted_pos = np.take_along_axis(cpos, order, axis=1)
                        scores = _scattered_runs_score(kv, sorted_pos, table4)
                    else:
                        scores = _batch_mean_logp(kv, runs, table4)
                    best.setdefault(name, []).append(float(scores.max()))
            per_w[model] = {
                name: {"k4_best": round(v[0], 3), "control_best": [round(x, 3) for x in v[1:]]}
                for name, v in best.items()
            }
        out[w] = {"permutations": len(perms), **per_w}
    lo, hi = calibration(13), calibration(11)
    out["reference_mean_logp"] = {"random": round((lo[0] + hi[0]) / 2, 3), "english": round((lo[1] + hi[1]) / 2, 3)}
    return out


def _scattered_runs_score(kv: np.ndarray, pos: np.ndarray, table4: np.ndarray) -> np.ndarray:
    """Mean quadgram log10 over every 4 consecutive ciphertext positions that are all crib positions."""
    rows, n = kv.shape
    total = np.zeros(rows)
    count = np.zeros(rows)
    for t in range(n - 3):
        ok = pos[:, t + 3] - pos[:, t] == 3
        idx = kv[:, t] * 17576 + kv[:, t + 1] * 676 + kv[:, t + 2] * 26 + kv[:, t + 3]
        total += np.where(ok, table4[idx], 0.0)
        count += ok
    return np.where(count > 0, total / np.maximum(count, 1), -99.0)


# ── Linear-recurrence keys ─────────────────────────────────────────────────


def recurrence_key(
    max_order: int = 7,
    ciphertext: str = K4,
    plain: dict[int, str] | None = None,
    keyword: str = "KRYPTOS",
) -> dict[str, list[dict[str, int]]]:
    """K[i] = c1*K[i-1] + ... + cn*K[i-n] + d (mod 26), any coefficients, any primer.

    Every window of n+1 consecutive crib positions gives one linear equation in the n+1
    unknowns (c1..cn, d). K4's two crib runs (13 and 11 letters) give 24 - 2n equations, so
    orders up to 7 are overdetermined. Solvable over Z26 iff solvable over GF(2) and GF(13).
    Returns the (order, equations) pairs that stay consistent.
    """
    plain = plain if plain is not None else crib_letters()
    out: dict[str, list[dict[str, int]]] = {}
    for name, (alpha, fn) in families(keyword).items():
        kv = key_values(alpha, fn, ciphertext, plain)
        hits = []
        for n in range(1, max_order + 1):
            rows, rhs = [], []
            for i in kv:
                if all(i - j in kv for j in range(1, n + 1)):
                    rows.append([kv[i - j] for j in range(1, n + 1)] + [1])
                    rhs.append(kv[i])
            if len(rows) <= n + 1:
                continue
            if _solvable_mod_prime(rows, rhs, 2) and _solvable_mod_prime(rows, rhs, 13):
                hits.append({"order": n, "equations": len(rows)})
        out[name] = hits
    return out


def recurrence_testable_orders(plain: dict[int, str] | None = None, max_order: int = 12) -> list[int]:
    """Orders with more equations than unknowns for these crib positions."""
    plain = plain if plain is not None else crib_letters()
    pos = set(plain)
    return [
        n for n in range(1, max_order + 1) if sum(1 for i in pos if all(i - j in pos for j in range(1, n + 1))) > n + 1
    ]


# ── Arbitrary monoalphabetic step + periodic key ───────────────────────────


class _PotentialUnionFind:
    """Union-find carrying value differences mod 26: tracks val(x) - val(root)."""

    def __init__(self) -> None:
        self.parent: dict[str, str] = {}
        self.pot: dict[str, int] = {}

    def find(self, x: str) -> tuple[str, int]:
        if x not in self.parent:
            self.parent[x], self.pot[x] = x, 0
            return x, 0
        path = []
        while self.parent[x] != x:
            path.append(x)
            x = self.parent[x]
        root, acc = x, 0
        for node in reversed(path):
            acc = (acc + self.pot[node]) % 26
            self.pot[node] = acc
            self.parent[node] = root
        return root, self.pot[path[0]] if path else 0

    def union(self, a: str, b: str, diff: int) -> bool:
        """Impose val(a) - val(b) = diff. False if it contradicts earlier constraints."""
        ra, pa = self.find(a)
        rb, pb = self.find(b)
        if ra == rb:
            return (pa - pb) % 26 == diff % 26
        # val(a) = pa + v(ra), val(b) = pb + v(rb) -> v(ra) - v(rb) = diff - pa + pb
        self.parent[ra] = rb
        self.pot[ra] = (diff - pa + pb) % 26
        return True


def _alphabet_system_consistent(edges: list[tuple[str, str, int]], letters_prefix: str) -> bool:
    uf = _PotentialUnionFind()
    for a, b, d in edges:
        if not uf.union(a, b, d):
            return False
    # Bijection: two different letters in one component must get different values.
    seen: dict[tuple[str, int], str] = {}
    for a, _b, _d in edges:
        if not a.startswith(letters_prefix):
            continue
        root, pot = uf.find(a)
        other = seen.setdefault((root, pot), a)
        if other != a:
            return False
    return True


def general_alphabet_periodic(
    max_period: int = 26,
    ciphertext: str = K4,
    plain: dict[int, str] | None = None,
) -> dict[str, list[int]]:
    """Periodic key combined with an arbitrary (not keyword-built) alphabet on one side.

    - ``mixed_plain_alphabet``: C = s(P) + k[i mod p], s any bijection. Also covers Beaufort
      and variant forms and any letter-swap or phonetic masking that is letter-for-letter
      consistent, because those are all just a different s.
    - ``mixed_cipher_alphabet``: C = t(P + k[i mod p]) or t(k[i mod p] - P), t any bijection.

    The unknowns are the alphabet's values and the key, linked by difference equations mod
    26 and solved exactly with a union-find. Returns the consistent periods. With 13 distinct
    crib plaintext letters (or 17 ciphertext letters) plus p key slots and 24 equations, the
    test has teeth only for small p; ``testable_periods`` in the result says where.
    """
    plain = plain if plain is not None else crib_letters()
    items = sorted(plain.items())
    ci = {i: STANDARD.index(ciphertext[i]) for i, _ in items}
    pi = {i: STANDARD.index(p) for i, p in items}
    out: dict[str, list[int]] = {
        "mixed_plain_alphabet": [],
        "mixed_cipher_alphabet_add": [],
        "mixed_cipher_alphabet_sub": [],
    }
    for p in range(1, max_period + 1):
        # s(P) - (-k[r]) = C
        edges = [(f"P{plain[i]}", f"K{i % p}", ci[i]) for i, _ in items]
        if _alphabet_system_consistent(edges, "P"):
            out["mixed_plain_alphabet"].append(p)
        # t^-1(C) - k[r] = P
        edges = [(f"C{ciphertext[i]}", f"K{i % p}", pi[i]) for i, _ in items]
        if _alphabet_system_consistent(edges, "C"):
            out["mixed_cipher_alphabet_add"].append(p)
        # t^-1(C) = k[r] - P  ->  t^-1(C) - k[r] = -P
        edges = [(f"C{ciphertext[i]}", f"K{i % p}", -pi[i]) for i, _ in items]
        if _alphabet_system_consistent(edges, "C"):
            out["mixed_cipher_alphabet_sub"].append(p)
    return out


def general_alphabet_control_rate(period: int, trials: int = 200, seed: int = 0) -> float:
    """Share of random ciphertexts (same cribs) that pass ``mixed_plain_alphabet`` at ``period``."""
    rng = random.Random(seed)
    hits = 0
    for _ in range(trials):
        ct = "".join(rng.choice(STANDARD) for _ in range(len(K4)))
        hits += period in general_alphabet_periodic(max_period=period, ciphertext=ct)["mixed_plain_alphabet"]
    return hits / trials


# ── Dial keys (clock face, compass, 24-hour ring) ──────────────────────────

DIALS: dict[str, int] = {
    "12-hour face": 12,
    "24-hour ring (Weltzeituhr)": 24,
    "minutes / seconds": 60,
    "compass degrees": 360,
    "12-hour face in minutes": 720,
    "24-hour ring in minutes": 1440,
}


def dial_key_scan(
    dials: dict[str, int] | None = None,
    ciphertext: str = K4,
    plain: dict[int, str] | None = None,
    keyword: str = "KRYPTOS",
) -> dict[str, dict[str, list[dict[str, int]]]]:
    """Key read from a dial that advances ``step`` positions per letter from ``start``.

    Reading at letter i: r = (start + step * i) mod N. Two rules turn a reading into a key value:
    ``scaled`` = floor(r * 26 / N) + b and ``mod26`` = r + b (mod 26), with any offset b.
    Exhaustive over every start, step and offset for each dial size N.
    """
    dials = dials if dials is not None else DIALS
    plain = plain if plain is not None else crib_letters()
    pos = np.array(sorted(plain), dtype=np.int64)
    out: dict[str, dict[str, list[dict[str, int]]]] = {}
    for name, (alpha, fn) in families(keyword).items():
        kv = np.array([v for _, v in sorted(key_values(alpha, fn, ciphertext, plain).items())], dtype=np.int64)
        hits: dict[str, list[dict[str, int]]] = {}
        for label, n in dials.items():
            found = []
            steps = np.arange(n, dtype=np.int64)
            for start in range(n):
                r = (start + steps[:, None] * pos[None, :]) % n  # (steps, cribs)
                for rule in ("scaled", "mod26"):
                    v = (r * 26) // n if rule == "scaled" else r % 26
                    diff = (kv[None, :] - v) % 26
                    ok = np.all(diff == diff[:, :1], axis=1)
                    for s in np.flatnonzero(ok)[:5]:
                        found.append({"start": start, "step": int(s), "rule": rule, "offset": int(diff[s, 0])})
            hits[label] = found
        out[name] = hits
    return out


# ── Routes along a compass bearing ─────────────────────────────────────────


def bearing_route(n: int, width: int, bearing_deg: float) -> list[int]:
    """Cell order for reading an n-letter text written in rows of ``width`` along a bearing.

    Lines run in the bearing's direction (0 = up the page, 90 = right). Cells are grouped into
    parallel lines by their perpendicular offset (scaled so axis and diagonal bearings give
    rows, columns and diagonals exactly), lines taken left to right across the bearing, each
    line read in the bearing's direction.
    """
    th = math.radians(bearing_deg)
    dx, dy = math.sin(th), -math.cos(th)  # screen coords: row index increases downward
    spacing = max(abs(dx), abs(dy))
    cells = []
    for i in range(n):
        r, c = divmod(i, width)
        along = c * dx + r * dy
        across = -c * dy + r * dx
        cells.append((round(across / spacing), round(along, 6), i))
    return [i for _, _, i in sorted(cells)]


def bearing_route_mappings(
    n: int = 97, widths: Iterable[int] = range(4, 25), step_deg: float = 1.0
) -> tuple[list[list[int]], list[dict[str, Any]]]:
    """Distinct bearing routes (and their inverses) over the widths and bearings given."""
    seen: set[tuple[int, ...]] = set()
    maps, labels = [], []
    deg = 0.0
    bearings = []
    while deg < 360:
        bearings.append(round(deg, 3))
        deg += step_deg
    for w in widths:
        for b in bearings:
            route = bearing_route(n, w, b)
            inv = [0] * n
            for j, i in enumerate(route):
                inv[i] = j
            for direction, perm in (("read_along", inv), ("write_along", route)):
                key = tuple(perm)
                if key in seen:
                    continue
                seen.add(key)
                maps.append(perm)
                labels.append({"width": w, "bearing": b, "direction": direction})
    return maps, labels


def bearing_route_scan(
    widths: Iterable[int] = range(4, 25),
    periods: Iterable[int] = range(1, 23),
    ciphertext: str = K4,
    plain: dict[int, str] | None = None,
    keyword: str = "KRYPTOS",
    step_deg: float = 1.0,
) -> dict[str, Any]:
    """Bearing routes composed with a periodic key, either layer order.

    ``perm[i]`` is the ciphertext position that holds plaintext letter i.
    """
    plain = plain if plain is not None else crib_letters()
    maps, labels = bearing_route_mappings(len(ciphertext), widths, step_deg)
    positions = sorted(plain)
    cpos = np.array([[m[i] for i in positions] for m in maps], dtype=np.int64)
    return {"mappings": len(maps), **_scan_mappings(cpos, labels, ciphertext, plain, list(periods), keyword, 5)}


# ── Long keys spelled from the Kryptos vocabulary ─────────────────────────


def vocabulary_phrase_keys(
    words: Iterable[str] | None = None,
    max_words: int = 3,
    min_len: int = 27,
    max_len: int = 60,
    ciphertext: str = K4,
    plain: dict[int, str] | None = None,
    keyword: str = "KRYPTOS",
) -> dict[str, Any]:
    """Keys longer than the cribs can pin down, spelled by chaining 2-3 Kryptos words.

    A key like PALIMPSESTABSCISSAKRYPTOS repeated with period len(phrase) is fully known, so
    every crib letter checks it directly, at every starting offset. Covers ordered phrases
    of up to ``max_words`` words from ``crib_constraints.KRYPTOS_VOCABULARY`` whose length
    is in [min_len, max_len]. Returns the number of phrases tested and any that fit.
    """
    from .crib_constraints import KRYPTOS_VOCABULARY

    words = sorted({w.upper() for w in (words or KRYPTOS_VOCABULARY)})
    plain = plain if plain is not None else crib_letters()
    fams = {name: (alpha, key_values(alpha, fn, ciphertext, plain)) for name, (alpha, fn) in families(keyword).items()}
    tested, hits = 0, []
    for k in range(2, max_words + 1):
        for combo in itertools.product(words, repeat=k):
            phrase = "".join(combo)
            if not min_len <= len(phrase) <= max_len:
                continue
            tested += 1
            n = len(phrase)
            for name, (alpha, kv) in fams.items():
                kvals = [alpha.index(ch) for ch in phrase]
                for off in range(n):
                    if all(kvals[(i + off) % n] == v for i, v in kv.items()):
                        hits.append({"phrase": phrase, "family": name, "offset": off})
    return {"phrases_tested": tested, "hits": hits}


# ── Wide columnar transpositions by backtracking ───────────────────────────


def _columnar_backtrack(
    width: int,
    period: int,
    model: str,
    alpha: str,
    fn: Any,
    ciphertext: str,
    plain: dict[int, str],
    max_solutions: int,
) -> tuple[list[list[int]], int, bool]:
    """Column orders consistent with a periodic key, found by depth-first search.

    Columns are placed in reading order; placing a column fixes the ciphertext position of
    every crib letter in it, so its key value and key slot are known and checked at once.
    Returns (orders, nodes visited, truncated).
    """
    n = len(ciphertext)
    col_len = [(n - c + width - 1) // width for c in range(width)]
    cribs_in = [
        [(j // width, j, alpha.index(p)) for j, p in sorted(plain.items()) if j % width == c] for c in range(width)
    ]
    cidx = [alpha.index(ch) for ch in ciphertext]
    slots: dict[int, int] = {}
    used = [False] * width
    order: list[int] = []
    found: list[list[int]] = []
    nodes = 0
    sub_first = model == "sub_then_trans"

    def rec(offset: int) -> bool:
        nonlocal nodes
        nodes += 1
        if len(order) == width:
            found.append(list(order))
            return len(found) >= max_solutions
        for c in range(width):
            if used[c]:
                continue
            added = []
            ok = True
            for r, j, pv in cribs_in[c]:
                cp = offset + r
                k = fn(cidx[cp], pv)
                s = j % period if sub_first else cp % period
                have = slots.get(s)
                if have is None:
                    slots[s] = k
                    added.append(s)
                elif have != k:
                    ok = False
                    break
            if ok:
                used[c] = True
                order.append(c)
                if rec(offset + col_len[c]):
                    return True
                used[c] = False
                order.pop()
            for s in added:
                del slots[s]
        return False

    truncated = rec(0)
    return found, nodes, truncated


def _decrypt_columnar_periodic(
    order: list[int], width: int, period: int, alpha: str, fn: Any, ciphertext: str, plain: dict[int, str]
) -> str | None:
    """Full decryption for a sub-then-transpose survivor when the cribs fix every key slot."""
    n = len(ciphertext)
    col_len = [(n - c + width - 1) // width for c in range(width)]
    start, off = {}, 0
    for c in order:
        start[c], off = off, off + col_len[c]
    key = {}
    for j, ch in plain.items():
        key[j % period] = fn(alpha.index(ciphertext[start[j % width] + j // width]), alpha.index(ch))
    if len(key) < period:
        return None
    inverse = {(cv, k): pv for cv in range(26) for pv in range(26) for k in [fn(cv, pv)]}
    out = []
    for j in range(n):
        cv = alpha.index(ciphertext[start[j % width] + j // width])
        out.append(alpha[inverse[(cv, key[j % period])]])
    return "".join(out)


def wide_columnar_scan(
    widths: Iterable[int] = range(10, 13),
    periods: Iterable[int] = range(1, 23),
    ciphertext: str = K4,
    plain: dict[int, str] | None = None,
    keyword: str = "KRYPTOS",
    max_solutions: int = 20_000,
) -> dict[int, Any]:
    """Columnar widths beyond brute force (10! and up) + periodic key, either order, exactly.

    Depth-first search over column orders with crib-key pruning; gives the same survivors as
    ``crib_constraints.columnar_period_scan`` where both run. Survivors whose cribs fix every key
    slot (sub-then-transpose, period <= 17 for K4) are decrypted in full and scored with
    ``english_z``: a real solution reads as English (about 1), chance survivors as noise.
    """
    plain = plain if plain is not None else crib_letters()
    out: dict[int, Any] = {}
    for w in widths:
        per_model: dict[str, Any] = {}
        for model in ("sub_then_trans", "trans_then_sub"):
            per_family: dict[str, Any] = {}
            for name, (alpha, fn) in families(keyword).items():
                per_period = {}
                for p in periods:
                    orders, nodes, truncated = _columnar_backtrack(
                        w, p, model, alpha, fn, ciphertext, plain, max_solutions
                    )
                    entry: dict[str, Any] = {"survivors": len(orders), "nodes": nodes, "truncated": truncated}
                    if orders and model == "sub_then_trans":
                        scores = [
                            english_z(_noncrib_text(t, plain))
                            for t in (
                                _decrypt_columnar_periodic(o, w, p, alpha, fn, ciphertext, plain) for o in orders[:500]
                            )
                            if t is not None
                        ]
                        if scores:
                            entry["best_english_z"] = round(max(scores), 3)
                    if orders:
                        entry["examples"] = orders[:3]
                    per_period[p] = entry
                per_family[name] = per_period
            per_model[model] = per_family
        out[w] = per_model
    return out


